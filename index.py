# EXPANDED GPU SEARCH
@app.get("/gpus/search", dependencies=[Depends(verify_api_key)])
def search_gpus(
    q: str = Query(..., min_length=1)
):
    q = q.lower().strip()

    results = []

    for gpu in gpus:
        searchable_text = " ".join([
            str(gpu["id"]),
            gpu["brand"],
            gpu["model"],
            gpu["architecture"],
            gpu["vram"],
            str(gpu["cuda_cores"]),
            gpu["memory_bus"],
            gpu["power"],
            gpu["base_clock"],
            gpu["boost_clock"],
            gpu["recommended_psu"],
            gpu["release_date"],
            gpu["description"]
        ]).lower()

        if q in searchable_text:
            results.append(gpu)

    return {
        "query": q,
        "count": len(results),
        "results": results
    }
    
# GET ONE GPU
@app.get("/gpus/{gpu_id}", dependencies=[Depends(verify_api_key)])
def get_gpu(gpu_id: int):

    for gpu in gpus:
        if gpu["id"] == gpu_id:
            return gpu

    raise HTTPException(
        status_code=404,
        detail="GPU not found."
    )


