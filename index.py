from fastapi import FastAPI, HTTPException, Query, Depends, Header
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field
from typing import Literal, Optional
from datetime import datetime, timezone

class GPU(BaseModel):
    id: int = Field(gt=0)
    brand: Literal["NVIDIA", "AMD", "Intel"]
    manufacturer: Literal[
        "NVIDIA", "AMD", "Intel", "ASUS", "MSI", "Gigabyte", "Zotac", "PNY",
        "Palit", "Colorful", "Gainward", "Inno3D", "EVGA", "PowerColor",
        "Sapphire", "XFX", "ASRock"
    ]
    model: str = Field(min_length=1)
    series: str = Field(min_length=1)
    architecture: str = Field(min_length=1)
    vram: str = Field(min_length=1)
    memory_type: Literal["DDR3", "GDDR5", "GDDR5X", "GDDR6", "GDDR6X", "GDDR7"]
    cuda_cores: int = Field(ge=0)
    core_count: int = Field(ge=0)
    core_type: Literal["CUDA Cores", "Stream Processors", "Xe Cores"]
    memory_bus: str = Field(min_length=1)
    memory_bandwidth_gbps: float = Field(
        gt=0, description="Memory bandwidth in GB/s (gigabytes per second)."
    )
    power: str = Field(min_length=1)
    base_clock: str = Field(min_length=1)
    boost_clock: str = Field(min_length=1)
    recommended_psu: str = Field(min_length=1)
    process_node_nm: int = Field(gt=0)
    pcie_interface: Literal[
        "PCIe 2.0 x8", "PCIe 2.0 x16", "PCIe 3.0 x4", "PCIe 3.0 x16",
        "PCIe 4.0 x8", "PCIe 4.0 x16", "PCIe 5.0 x8", "PCIe 5.0 x16"
    ]
    launch_price_usd: Optional[float] = Field(..., ge=0)
    release_date: str = Field(min_length=1)
    description: str = Field(min_length=1)
    

API_KEY = "apinilance"

def verify_api_key(x_api_key: str = Header(None)):
    if x_api_key != API_KEY:
        raise HTTPException(
            status_code=401,
            detail="Invalid or missing API key"
        )
    return x_api_key

