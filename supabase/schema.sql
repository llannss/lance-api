-- GPU Finder API: database structure for Supabase (PostgreSQL)
-- Run this first in the Supabase SQL Editor, then run seed.sql.

create table if not exists public.gpus (
    id bigint generated by default as identity (maxvalue 9007199254740991) primary key,

    brand text not null
        check (brand in ('NVIDIA', 'AMD', 'Intel')),
    manufacturer text not null
        check (manufacturer in (
            'NVIDIA', 'AMD', 'Intel', 'ASUS', 'MSI', 'Gigabyte', 'Zotac', 'PNY',
            'Palit', 'Colorful', 'Gainward', 'Inno3D', 'EVGA', 'PowerColor',
            'Sapphire', 'XFX', 'ASRock'
        )),
    model text not null
        check (char_length(model) between 1 and 120),
    series text not null
        check (char_length(series) between 1 and 120),
    architecture text not null
        check (char_length(architecture) between 1 and 120),
    vram text not null
        check (char_length(vram) between 1 and 120),
    memory_type text not null
        check (memory_type in ('DDR3', 'GDDR5', 'GDDR5X', 'GDDR6', 'GDDR6X', 'GDDR7')),
    cuda_cores integer not null
        check (cuda_cores >= 0),
    core_count integer not null
        check (core_count >= 0),
    core_type text not null
        check (core_type in ('CUDA Cores', 'Stream Processors', 'Xe Cores')),
    memory_bus text not null
        check (char_length(memory_bus) between 1 and 120),
    memory_bandwidth_gbps double precision not null
        check (memory_bandwidth_gbps > 0 and memory_bandwidth_gbps <= 1000000),
    power text not null
        check (char_length(power) between 1 and 120),
    base_clock text not null
        check (char_length(base_clock) between 1 and 120),
    boost_clock text not null
        check (char_length(boost_clock) between 1 and 120),
    recommended_psu text not null
        check (char_length(recommended_psu) between 1 and 120),
    process_node_nm integer not null
        check (process_node_nm > 0),
    pcie_interface text not null
        check (pcie_interface in (
            'PCIe 2.0 x8', 'PCIe 2.0 x16', 'PCIe 3.0 x4', 'PCIe 3.0 x16',
            'PCIe 4.0 x8', 'PCIe 4.0 x16', 'PCIe 5.0 x8', 'PCIe 5.0 x16'
        )),
    launch_price_usd double precision
        check (launch_price_usd is null or (launch_price_usd >= 0 and launch_price_usd <= 1000000000)),
    release_date date not null,
    description text not null
        check (char_length(description) between 1 and 4000),

    -- Lowercase text the API searches with a keyword. The database fills this in.
    search_text text generated always as (
        lower(
            brand || ' ' || manufacturer || ' ' || model || ' ' || series || ' ' ||
            architecture || ' ' || vram || ' ' || memory_type || ' ' ||
            cuda_cores::text || ' ' || core_type || ' ' || memory_bus || ' ' ||
            power || ' ' || base_clock || ' ' || boost_clock || ' ' ||
            recommended_psu || ' ' || pcie_interface || ' ' || description
        )
    ) stored
);

-- The same brand, manufacturer and model cannot be added twice, ignoring case.
create unique index if not exists gpus_brand_manufacturer_model_key
    on public.gpus (lower(brand), lower(manufacturer), lower(model));

-- Security: browsers cannot read or change the table directly.
-- Only the backend, which uses the secret key, can.
alter table public.gpus enable row level security;
revoke all on table public.gpus from anon, authenticated;
grant select, insert, update, delete on table public.gpus to service_role;
